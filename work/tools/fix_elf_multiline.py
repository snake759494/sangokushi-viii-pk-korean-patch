FMT = re.compile(r"%[-0-9.]*[sdxXcu]|\[[0-9]b")


def width(s):
    return sum(1 if ord(c) < 0x80 or 0xFF61 <= ord(c) <= 0xFF9F else 2 for c in s)


def main():
    rows = list(csv.DictReader(open(P, encoding="utf-8"), delimiter="\t", quoting=csv.QUOTE_NONE))
    by = {int(r["offset"]): r for r in rows}
    jp = elf_strings.unesc(by[5284096]["jp"])
    last = jp.split(N)[-1].replace("終了", "완료").replace("中断", "중단")
    T[5284096] = ("삼국지 8 with 파워업 키트의\n게임 데이터를 설치하고 있습니다\n전원을 끄거나\n"
                  '"PlayStation BB Unit"을 뽑거나\n하지 마십시오\n\n' + last)
    errs = 0
    for o, ko in T.items():
        r = by[o]
        j = elf_strings.unesc(r["jp"])
        cap = int(r["cap"])
        b = ko_enc.encode(ko)
        e = []
        if j.count(N) != ko.count(N):
            e.append("줄 수 %d/%d" % (j.count(N), ko.count(N)))
        if FMT.findall(j) != FMT.findall(ko):
            e.append("서식 %s/%s" % (FMT.findall(j), FMT.findall(ko)))
        if len(b) + 1 > cap:
            e.append("길이 %d+1 > %d" % (len(b), cap))
        if re.search(r"[\u3040-\u30ff\u4e00-\u9fff]", ko.replace("・", "")):
            e.append("가나·한자")
        wj = max(width(x) for x in j.split(N))
        wk = max(width(x) for x in ko.split(N))
        if e:
            errs += 1
            print("오류", o, e, ko)
        elif wk > max(wj + 8, 40):
            print("폭 주의", o, wj, wk, ko.split(N))
        r["ko"] = elf_strings.esc(ko)
    if errs:
        raise SystemExit("오류 %d개 - 쓰지 않음" % errs)
    with open(P, "w", encoding="utf-8", newline="\n") as f:
        f.write("offset\tcap\tjp\tko\n")
        for r in sorted(rows, key=lambda r: int(r["offset"])):
            f.write("\t".join(str(r[k] or "") for k in ("offset", "cap", "jp", "ko")) + "\n")
    print("고친 문자열 %d개" % len(T))


if __name__ == "__main__":
    main()
