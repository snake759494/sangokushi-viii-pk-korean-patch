# 순수 종조사 매크로(ね·な·わ·ぞ·よ …)는 비운다.
# 일본어는 「~ました + ね」처럼 종결어미 뒤에 조사를 덧붙이지만 한국어는
# 「~했습니다 + 군요」를 겹칠 수 없다. 앞 매크로가 이미 문장을 끝내므로 비우는 것이 맞다.
# (실측: 이런 매크로 1,518곳 가운데 대부분이 다른 매크로 바로 뒤에 온다)
PARTICLE_ONLY = {0x05AA, 0x05AB, 0x05AC, 0x05AD, 0x05AE,
                 0x05D8, 0x05D9, 0x05DA, 0x05E2, 0x05E4, 0x05E5}


def main():
    rows = list(csv.DictReader(open(SRC, encoding="utf-8"), delimiter="\t",
                               quoting=csv.QUOTE_NONE))
    miss = []
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("idx\tcode\tslot\tcond\tjp\tko\n")
        prev = {}
        for k, r in enumerate(rows):
            i = int(r["idx"]); jp = r["jp"]
            before = rows[k - 1]["jp"] if k and int(rows[k - 1]["idx"]) == i else ""
            ko = OVER.get((i, jp), D.get(jp))
            # 이름 변수 뒤의 殿/様 는 호칭 접미사
            if jp in ("殿", "様") and before == "N":
                ko = " 님"
            if 0x055A + i in PARTICLE_ONLY:
                ko = ""
            if ko is None:
                miss.append((i, jp))
                ko = ""
            f.write("%s\t%s\t%s\t%s\t%s\t%s\n" % (r["idx"], r["code"], r["slot"], r["cond"], jp, ko))
    print("칸 %d개, 대응 없는 낱말 %d종" % (len(rows), len(set(m[1] for m in miss))))
    for m in sorted(set(miss))[:40]:
        print("   미대응 idx%d %s" % m)


if __name__ == "__main__":
    main()
